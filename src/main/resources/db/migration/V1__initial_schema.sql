-- AeroRoster V1: new PostgreSQL schema, designed from the legacy Oracle DBMS domain.
-- Requires an EMPTY dedicated database. All times are UTC-aware instants.

CREATE TABLE airport (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iata_code VARCHAR(3) NOT NULL UNIQUE CHECK (iata_code ~ '^[A-Z]{3}$'),
  name VARCHAR(120) NOT NULL,
  city VARCHAR(80) NOT NULL,
  country VARCHAR(80) NOT NULL
);

CREATE TABLE aircraft_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model VARCHAR(60) NOT NULL UNIQUE,
  manufacturer VARCHAR(80) NOT NULL,
  capacity INTEGER NOT NULL CHECK (capacity > 0),
  min_cabin_crew INTEGER NOT NULL CHECK (min_cabin_crew BETWEEN 1 AND 12)
);

CREATE TABLE aircraft (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration VARCHAR(24) NOT NULL UNIQUE,
  aircraft_type_id BIGINT NOT NULL REFERENCES aircraft_type(id),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE crew (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('PILOT','COPILOT','CABIN_CREW')),
  license_no VARCHAR(30) NOT NULL UNIQUE,
  experience_years INTEGER NOT NULL CHECK (experience_years >= 0),
  contact_no VARCHAR(20) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE qualification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aircraft_type_id BIGINT NOT NULL REFERENCES aircraft_type(id),
  required_role VARCHAR(20) NOT NULL CHECK (required_role IN ('PILOT','COPILOT','CABIN_CREW')),
  UNIQUE (aircraft_type_id, required_role)
);

CREATE TABLE crew_qualification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crew_id BIGINT NOT NULL REFERENCES crew(id),
  qualification_id BIGINT NOT NULL REFERENCES qualification(id),
  valid_until DATE,
  UNIQUE (crew_id, qualification_id)
);

CREATE TABLE flight (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_number VARCHAR(15) NOT NULL,
  source_airport_id BIGINT NOT NULL REFERENCES airport(id),
  destination_airport_id BIGINT NOT NULL REFERENCES airport(id),
  aircraft_id BIGINT NOT NULL REFERENCES aircraft(id),
  departure_time TIMESTAMPTZ NOT NULL,
  arrival_time TIMESTAMPTZ NOT NULL,
  status VARCHAR(15) NOT NULL DEFAULT 'SCHEDULED'
    CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT chk_flight_times CHECK (arrival_time > departure_time),
  CONSTRAINT chk_distinct_airports CHECK (source_airport_id <> destination_airport_id),
  CONSTRAINT uq_flight_instance UNIQUE (flight_number, departure_time)
);

CREATE TABLE crew_unavailability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crew_id BIGINT NOT NULL REFERENCES crew(id),
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  reason VARCHAR(200) NOT NULL,
  CONSTRAINT chk_unavailability_times CHECK (end_time > start_time)
);

CREATE TABLE duty_assignment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crew_id BIGINT NOT NULL REFERENCES crew(id),
  flight_id BIGINT NOT NULL REFERENCES flight(id),
  assigned_role VARCHAR(20) NOT NULL CHECK (assigned_role IN ('PILOT','COPILOT','CABIN_CREW')),
  duty_start_time TIMESTAMPTZ NOT NULL,
  duty_end_time TIMESTAMPTZ NOT NULL,
  status VARCHAR(15) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_duty_times CHECK (duty_end_time > duty_start_time)
);

CREATE UNIQUE INDEX uq_active_crew_flight ON duty_assignment (crew_id, flight_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_active_assignment_crew_window ON duty_assignment (crew_id, duty_start_time, duty_end_time) WHERE status = 'ACTIVE';
CREATE INDEX idx_unavailability_crew_window ON crew_unavailability (crew_id, start_time, end_time);
CREATE INDEX idx_flight_aircraft_window ON flight (aircraft_id, departure_time, arrival_time);
CREATE INDEX idx_flight_departure_time ON flight (departure_time);
CREATE INDEX idx_crew_qualification_crew ON crew_qualification (crew_id);
CREATE INDEX idx_duty_assignment_flight ON duty_assignment (flight_id);

-- DB-managed auditing is retained as an explicit continuation of the Oracle project.
CREATE TABLE flight_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id BIGINT NOT NULL,
  flight_number VARCHAR(15) NOT NULL,
  action VARCHAR(10) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
  action_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION audit_flight_change() RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    INSERT INTO flight_audit (flight_id, flight_number, action)
    VALUES (OLD.id, OLD.flight_number, TG_OP);
    RETURN OLD;
  ELSE
    INSERT INTO flight_audit (flight_id, flight_number, action)
    VALUES (NEW.id, NEW.flight_number, TG_OP);
    RETURN NEW;
  END IF;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_flight_audit
AFTER INSERT OR UPDATE OR DELETE ON flight
FOR EACH ROW EXECUTE FUNCTION audit_flight_change();
